"""Render THIRD_PARTY.md from third_party/deps.toml.

Run: <python> -I tools/thirdparty.py [--check]   (default writes THIRD_PARTY.md)
Ref: docs/decisions/0001-architecture.md D7.2 (borrowed code), D7.4 (NVIDIA risk), D9.6.
"""
import os
import sys
import tomllib

RISK = (
    "NVIDIA material is never committed and never shipped: the OptiX headers are fetched at "
    "build time from `NVIDIA/optix-dev` at a pinned commit, and DLSS/NGX DLLs, Streamline, "
    "NVRTC and every CUDA toolkit file other than statically linked cudart stay out. Compiled "
    "kernels (SASS, PTX, OptiX modules) are shipped, as Cycles does. Risk: the CUDA EULA "
    "section 1.2, the DesignWorks licence 2.1(xii) and the RTX SDK licence 4(e) touch this "
    "arrangement and have not been reviewed by a lawyer."
)


def cell(d, k):
    return str(d.get(k, "")).replace("|", "/")


def render(data):
    o = ["# Third-party notices", "",
         "Generated by `tools/thirdparty.py` from `third_party/deps.toml`; do not edit.", "",
         "## Dependencies", "",
         "| Name | Version | Licence | Kind | SHA-256 | Purpose | Record |",
         "|---|---|---|---|---|---|---|"]
    for d in data.get("dep", []):
        o.append("| " + " | ".join([cell(d, "name"), cell(d, "version"), cell(d, "spdx"), cell(d, "kind"),
                                    "`" + cell(d, "sha256") + "`", cell(d, "purpose"),
                                    cell(d, "record")]) + " |")
    o += ["", "## Borrowed code", ""]
    b = data.get("borrowed", [])
    if not b:
        o.append("None yet.")
    else:
        o += ["| Source | Commit | Licence | Our files |", "|---|---|---|---|"]
        for r in b:
            o.append("| " + " | ".join(cell(r, k) for k in ("url", "commit", "spdx", "files")) + " |")
    o += ["", "## NVIDIA licence risk", "", RISK, ""]
    return "\n".join(o)


def render_requirements(data):
    """pip --require-hashes file for hosted CI, from the tool-python entries (0009 d2)."""
    o = ["# Generated by tools/thirdparty.py from third_party/deps.toml; do not edit."]
    for d in data.get("dep", []):
        if d.get("kind") == "tool-python":
            o.append(f"{d['name']}=={d['version']} --hash=sha256:{d['sha256']}")
    return "\n".join(o) + "\n"


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "third_party", "deps.toml"), "rb") as f:
        data = tomllib.load(f)
    outs = [(os.path.join(root, "THIRD_PARTY.md"), render(data), "THIRD_PARTY.md"),
            (os.path.join(root, ".github", "ci-requirements.txt"), render_requirements(data),
             ".github/ci-requirements.txt")]
    if "--check" in sys.argv:
        ok = True
        for path, want, label in outs:
            try:
                with open(path, encoding="utf-8", newline="") as f:
                    same = f.read().replace("\r\n", "\n") == want
            except OSError:
                same = False
            print(f"{label} is up to date" if same else f"{label} is stale: run tools/thirdparty.py")
            ok = ok and same
        return 0 if ok else 1
    for path, want, _ in outs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
